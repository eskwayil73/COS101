# Purpose: this program calculates the total number of chairs in a classroom woth 6 rows and 8 chairs on each row

rows = 6
chair_per_row = 8
totalchairs = rows * chair_per_row

print("There are", rows, "rows in a classroom")
print("And there are", chair_per_row, "chairs in each row")
print("Therefore, there are", totalchairs, "chairs in the classroom")

